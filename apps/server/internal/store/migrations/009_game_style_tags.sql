-- 사람이 그 판에서 실제로 짠 囲い·전법·戦型. 설계 근거는 docs/06-status.md §77.
--
-- **실행은 사람이 DB 클라이언트로 직접 한다** — 배포도 compose도 안 돌린다(deploy/README.md §4).

-- 표를 새로 파지 않고 `games` 에 배열 한 칸을 붙인다.
--
-- 이름은 **판당 한 번**만 뜻이 있다 — 같은 囲い를 두 수에 걸쳐 유지해도 「美濃囲いを組んだ」는
-- 한 번이고, 그래서 (game_id, code) 가 곧 유일 키다. 표로 파면 그 유일성을 제약으로 또
-- 적어야 하고, 마이페이지가 세는 것은 판 수라 어느 手数였는지는 아무도 안 묻는다.
--
-- **`kind` 를 안 적는다.** 코드에서 축(囲い·전법·戦型)이 나오고 그 표는 internal/tag 이
-- 소유한다(docs/09-tags.md). 여기 적으면 두 벌이 되고, 축을 옮기는 날 한쪽만 낡는다.
--
-- **手筋은 안 담는다.** 이름의 정확도가 아직 프로덕션 수준이 아니라 보류 중이고(§45 — 한 판
-- 8건 중 3건 오진), 「당신이 쓴 手筋」으로 화면에 세우는 것은 그 오진을 사람의 기록으로
-- 굳히는 일이다. 담을 자리는 이 칸 그대로이므로 정확도가 서면 그때 넣는다.
ALTER TABLE games ADD COLUMN style_tags text[] NOT NULL DEFAULT '{}';

-- 마이페이지가 `user_id` 로 걸러 `unnest` 한다. 판 수가 사람당 수십이라 인덱스가 필요한
-- 크기는 아니지만, 배열을 GIN 으로 걸어 두면 나중에 「이 전법으로 둔 판」을 되찾을 수 있다 —
-- `edges.tags` 와 같은 모양이다(001_init.sql).
CREATE INDEX games_style_tags_idx ON games USING gin (style_tags);
