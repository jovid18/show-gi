package game

// 詰み 게이지 — **상대 玉 쪽 하나만 그린다.**
//
// 갈려 있던 결정을 닫은 자리다. 01-core.md §7은 「내 詰み만」, 06-status.md §21 ③은
// 「양쪽 다」로 적혀 있었고, 두 문장이 같은 「내」를 서로 다르게 읽고 있었다.
//
// 채택한 것은 앞쪽이다. 근거는 **보호가 이미 다른 데서 돌고 있다**는 것이다 — 詰まされる
// 수를 두면 승률 낙폭이 멀쩡히 움직여 제지형 개입이 그 수를 물린다(01-core.md §2).
// 내 玉이 위험한 것을 게이지로 또 그릴 이유가 없고, 그리면 상대의 계획을 알려주는 일이
// 된다. 그래서 테두리에 불이 붙으면 **언제나 「내가 가까워졌다」**는 뜻이고, 하나뿐이라
// 이기는 중인지 지는 중인지가 반대로 읽히지 않는다.

// MateHeatMax 는 게이지 세기의 상한이다. 화면이 단계 수를 알아야 곡선을 나눈다.
const MateHeatMax = 5

// mateHeat 는 詰み 手数를 게이지 세기로 옮긴다. 0이면 詰み이 없다(= 게이지가 꺼진다).
//
// **手数를 그대로 화면에 보내지 않기 위해 여기서 자른다.** 01-core.md §7의 게이지는
// 「수순도 手数도 알려주지 않는다」인데, 手数가 페이로드에 실려 있으면 그리지 않아도 이미
// 알려준 것이다 — 갇힘 힌트의 단계를 서버에서 자르는 것과 같은 자리다(buildHint).
//
// 구간은 §7의 「11→7→5→3→1」이 그대로다. solver 의 DepthLimit 이 11이라 手数는 홀수
// 1·3·5·7·9·11 중 하나로만 오지만, 그 한계는 환경변수라 짝수·더 큰 값에도 답이 있어야 한다.
func mateHeat(plies int) int {
	switch {
	case plies <= 0:
		return 0
	case plies <= 1:
		return 5
	case plies <= 3:
		return 4
	case plies <= 5:
		return 3
	case plies <= 7:
		return 2
	default:
		return 1
	}
}
